"""Check the bundled Mushaf text against Quranpedia's King Fahd Complex text.

data/quran.json takes its Arabic from quran-json 3.1.2 (QuranEnc). The challenge's scientific package names
the King Fahd Complex Mushaf and quranpedia.net, so this script compares every verse with Quranpedia's
«مصحف حفص بالخط العثماني من إصدار مجمع الملك فهد» (qpc-hafs, dump 2026-09-30), from a pinned snapshot in
github.com/risan/quran-json checked by sha256. It writes eval/mushaf_check.md.

Three levels of comparison for each verse:
  identical  the same characters;
  encoding   the same after normalising how marks are encoded (Unicode NFD, the older KFGQPC open-tanween
             code points U+0656/U+065E/U+0657 mapped to U+08F2/U+08F1/U+08F0, tatweel, spaces and
             direction marks removed, combining marks in a fixed order);
  skeleton   the same letters as the app matches them (app.normalize.skeleton_ar).

Usage: python eval/mushaf_check.py
"""
import hashlib
import json
import sys
import unicodedata
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app.normalize import skeleton_ar  # noqa: E402

URL = ("https://raw.githubusercontent.com/risan/quran-json/8528abfcb55d808562ae9675217c07890322178f/"
       "data/quranpedia/qpc-hafs.json")
SHA256 = "0136b913aeb5a6a0389681f988215791ddd848c4347f7cf5e9d2574db7f1da49"
OLD_TANWEEN = str.maketrans({"ٖ": "ࣲ", "ٞ": "ࣱ", "ٗ": "ࣰ"})
DROP = {"ـ", " ", "‏", "‎", " "}


def encoding_form(text: str) -> str:
    text = unicodedata.normalize("NFD", text).translate(OLD_TANWEEN)
    out, marks = [], []
    for ch in text:
        if ch in DROP:
            continue
        if unicodedata.combining(ch):
            marks.append(ch)
            continue
        out.extend(sorted(marks))
        marks = []
        out.append(ch)
    out.extend(sorted(marks))
    return "".join(out)


def main() -> None:
    raw = urllib.request.urlopen(URL, timeout=60).read()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SHA256:
        sys.exit(f"qpc-hafs: sha256 {digest} does not match the pinned snapshot")
    ref = {(v["chapter"], v["verse"]): v["text"] for s in json.loads(raw).values() for v in s}
    ours = {(s, a): t for s, a, t, *_ in json.loads((ROOT / "data" / "quran.json").read_text(encoding="utf-8"))["verses"]}

    counts = {"identical": 0, "encoding": 0, "skeleton": 0, "different": 0}
    notes = []
    for key in sorted(ours):
        a, b = ours[key], ref.get(key, "")
        if a == b:
            counts["identical"] += 1
        elif encoding_form(a) == encoding_form(b):
            counts["encoding"] += 1
        elif skeleton_ar(a) == skeleton_ar(b):
            counts["skeleton"] += 1
            notes.append((key, a, b))
        else:
            counts["different"] += 1
            notes.append((key, a, b))
    total = len(ours)
    same_letters = total - counts["different"]
    lines = [
        "# Mushaf text check · مطابقة نص المصحف",
        "",
        "Generated by `python eval/mushaf_check.py`. Bundled text (`data/quran.json`, from quran-json 3.1.2 / QuranEnc) "
        "against Quranpedia's King Fahd Complex Hafs text (qpc-hafs), pinned snapshot, sha256 `" + SHA256[:12] + "…`.",
        "",
        f"| Verses | Identical characters | Same after encoding normalisation | Same letters for matching only | Different |",
        "|---|---|---|---|---|",
        f"| {total} | {counts['identical']} | {counts['encoding']} | {counts['skeleton']} | {counts['different']} |",
        "",
        f"**{counts['identical'] + counts['encoding']} of {total}** verses are the same text, differing at most in how "
        f"marks are encoded; **{same_letters} of {total}** give the same result in the app's matching.",
        "",
    ]
    if notes:
        lines += ["## Verses that differ beyond encoding", "", "| Verse | Bundled | Quranpedia |", "|---|---|---|"]
        lines += [f"| {s}:{v} | {a} | {b} |" for (s, v), a, b in notes]
        lines.append("")
    (ROOT / "eval" / "mushaf_check.md").write_text("\n".join(lines), encoding="utf-8")
    print(counts)


if __name__ == "__main__":
    main()
