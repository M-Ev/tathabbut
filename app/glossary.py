def gloss_book(book: str) -> str | None:
    b = normalize_ar(book)
    if b in BOOKS:
        return BOOKS[b]
    if b.startswith("تخريج "):
        inner = gloss_book(b[len("تخريج "):])
        return f"Takhrij of {inner}" if inner else None
    for prefix, en in (("صحيح ", "Sahih"), ("ضعيف ", "Da'if")):
        if b.startswith(prefix) and b[len(prefix):] in _SHORT:
            return f"{en} {_SHORT[b[len(prefix):]]}"
    return None
