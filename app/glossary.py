"""English help for hadith grading terms and book titles, for readers who do not read Arabic.

Grading terms: the English is the Jamhara dictionary's own English headword (islamic-content.com/dictionary),
the term dictionary named in the challenge's scientific package, copied verbatim with a link to the entry.
Where Jamhara has no English entry for the hadith sense of a term, no English is shown and the link goes to
its Arabic entry. Nothing here is generated by the model, and the scholar's Arabic wording is always shown
verbatim; the English only says what the term means. Each term also has a category (accepted, weak, ...),
the tool's grouping used for colour and for noting that gradings differ; the grouping is reviewed by the
team's Sharia specialist.
"""
